"""Seed, verify and report the four demo projects (local database only).

HOW IT STAYS HONEST
* The only privileged step is `bootstrap_users`: it creates the fictional sign-in identities and the CREATE_PROJECT platform grant in the LOCAL
  auth shim (app.system on, one transaction). Everything else runs as the real actor through the real services: project creation (PM with the
  grant), membership (PM), schedule import -> build -> activate (PM), claims / corrections / withdrawals / clarification answers (Site Engineers),
  decisions (Supervisors), issues (Site Engineers and Supervisors). No ledger row is ever inserted directly.
* Refuses a non-empty database unless it is exactly the seeded state (then it only verifies). `reset_local` empties a local setuai_v2_* database
  first; it refuses anything else. Never targets hosted Supabase, never touches another database.
* Deterministic: fixed project / user ids and codes, fixed anchor date, no clock, no randomness. Internal row ids of imported and executed rows
  are generated by the database, so reproducibility is defined over external identifiers: `digest()` hashes the business content keyed by
  activity / resource ids, and two seeded databases have the same digest."""
